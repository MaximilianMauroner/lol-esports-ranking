function resolveBranding(team, official, leaguepedia) {
  const names = [team.name, ...(sourceAliases[team.name] ?? [])]
  const officialMatch = findSourceTeam(official, names)
  if (officialMatch) {
    return {
      name: team.name,
      code: officialMatch.code,
      source: 'lol-esports',
      sourceName: officialMatch.name,
      sourceUrl: 'https://lolesports.com',
      remoteLogoUrl: secureUrl(officialMatch.image),
    }
  }

  const leaguepediaMatch = findSourceTeam(leaguepedia, names)
  if (leaguepediaMatch) {
    return {
      name: team.name,
      code: leaguepediaMatch.code,
      source: 'leaguepedia',
      sourceName: leaguepediaMatch.name,
      sourceUrl: `https://lol.fandom.com/wiki/${encodeURIComponent(leaguepediaMatch.overviewPage.replaceAll(' ', '_'))}`,
      leaguepediaImage: leaguepediaMatch.image,
    }
  }

  return {
    name: team.name,
    code: manualCodes[team.name] ?? team.code,
    source: 'name-derived',
    sourceName: team.name,
  }
}

function findSourceTeam(sourceTeams, names) {
  for (const name of names) {
    const normalized = normalizeName(name)
    const match = sourceTeams.find((team) => normalizeName(team.name) === normalized || normalizeName(team.overviewPage) === normalized)
    if (match?.code) return match
  }
  return undefined
}

async function loadOfficialTeams(path) {
  let manifest
  try {
    manifest = JSON.parse(await readFile(path, 'utf8'))
  } catch {
    return []
  }
  const paths = [...(manifest.files?.lolEsportsJson ?? []), ...arrayArg(args.lolesportsJson ?? args['lolesports-json'])]
  const records = new Map()
  for (const rawPath of paths) {
    const filePath = resolveInputPath(rawPath, path)
    try {
      const snapshot = JSON.parse(await readFile(filePath, 'utf8'))
      visit(snapshot, (value) => {
        if (typeof value.name !== 'string' || typeof value.code !== 'string' || typeof value.image !== 'string') return
        const team = { name: value.name.trim(), code: value.code.trim(), image: value.image.trim() }
        records.set(`${normalizeName(team.name)}:${team.code}`, team)
      })
    } catch (error) {
      if (args.verbose) console.warn(`Skipped ${filePath}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  return [...records.values()]
}

async function loadLeaguepediaTeams() {
  const url = new URL(cargoUrl)
  url.searchParams.set('format', 'json')
  url.searchParams.set('limit', '5000')
  url.searchParams.set('tables', 'Teams')
  url.searchParams.set('fields', 'OverviewPage,Name,Short,Image,Region')
  const rows = await fetchJsonWithRetry(url)
  return rows.flatMap((row) => {
    const name = text(row.Name)
    const overviewPage = text(row.OverviewPage)
    const code = text(row.Short)
    if (!name || !overviewPage || !code) return []
    return [{ name, overviewPage, code, image: text(row.Image) }]
  })
}

async function resolveLeaguepediaImages(candidates) {
  const images = [...new Set(candidates.map((candidate) => candidate.leaguepediaImage).filter(Boolean))]
  const resolved = new Map()
  for (let index = 0; index < images.length; index += 40) {
    const batch = images.slice(index, index + 40)
    const url = new URL(apiUrl)
    url.searchParams.set('action', 'query')
    url.searchParams.set('format', 'json')
    url.searchParams.set('prop', 'imageinfo')
    url.searchParams.set('iiprop', 'url|mime')
    url.searchParams.set('titles', batch.map((image) => `File:${image}`).join('|'))
    const response = await fetchJsonWithRetry(url)
    for (const page of Object.values(response.query?.pages ?? {})) {
      const image = text(page.title).replace(/^File:/, '')
      const imageUrl = page.imageinfo?.[0]?.url
      if (image && imageUrl) resolved.set(image, secureUrl(imageUrl))
    }
  }
  return resolved
}

async function downloadLogo(teamName, remoteUrl) {
  try {
    const response = await fetchWithRetry(remoteUrl)
    const contentType = response.headers.get('content-type')?.split(';')[0].trim().toLowerCase()
    const extension = extensionFor(contentType, remoteUrl)
    if (!extension) throw new Error(`unsupported content type ${contentType ?? 'unknown'}`)
    const body = Buffer.from(await response.arrayBuffer())
    if (body.length < 100) throw new Error(`response was only ${body.length} bytes`)
    const fileName = `${slug(teamName)}${extension}`
    await writeFile(resolve(logoDirectory, fileName), body)
    return `/team-logos/${fileName}`
  } catch (error) {
    const existing = await existingLogo(teamName)
    console.warn(`Logo unavailable for ${teamName}: ${error instanceof Error ? error.message : String(error)}`)
    return existing
  }
}

async function existingLogo(teamName) {
  try {
    const prefix = `${slug(teamName)}.`
    const file = (await readdir(logoDirectory)).find((entry) => entry.startsWith(prefix))
    return file ? `/team-logos/${file}` : undefined
  } catch {
    return undefined
  }
}

async function fetchJsonWithRetry(url) {
  const response = await fetchWithRetry(url)
  const value = await response.json()
  if (value?.error) throw new Error(`${value.error.code ?? 'provider error'}: ${value.error.info ?? 'unknown error'}`)
  return value
}

async function fetchWithRetry(url) {
  let lastError
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      const response = await fetch(url, { headers: { 'user-agent': userAgent } })
      if (response.ok) return response
      lastError = new Error(`HTTP ${response.status} from ${new URL(url).hostname}`)
      if (response.status !== 429 && response.status < 500) break
    } catch (error) {
      lastError = error
    }
    await sleep(750 * 2 ** attempt)
  }
  throw lastError ?? new Error(`Unable to fetch ${url}`)
}

function visit(value, callback) {
  if (!value || typeof value !== 'object') return
  if (Array.isArray(value)) {
    for (const item of value) visit(item, callback)
    return
  }
  callback(value)
  for (const item of Object.values(value)) visit(item, callback)
}

function extensionFor(contentType, url) {
  if (contentType === 'image/png') return '.png'
  if (contentType === 'image/webp') return '.webp'
  if (contentType === 'image/jpeg') return '.jpg'
  if (contentType === 'image/svg+xml') return '.svg'
  const extension = extname(new URL(url).pathname).toLowerCase()
  return ['.png', '.webp', '.jpg', '.jpeg', '.svg'].includes(extension) ? extension.replace('.jpeg', '.jpg') : undefined
}

function resolveInputPath(input, manifest) {
  if (input.startsWith('/')) return input
  return resolve(resolve(manifest, '..'), input)
}

function normalizeName(value) {
  return text(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
}

function slug(value) {
  return text(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'team'
}

function secureUrl(value) {
  return text(value).replace(/^http:/, 'https:')
}

function withoutName(team) {
  return {
    code: team.code,
    source: team.source,
    sourceName: team.sourceName,
    ...(team.sourceUrl ? { sourceUrl: team.sourceUrl } : {}),
    ...(team.logo ? { logo: team.logo } : {}),
    ...(team.remoteLogoUrl ? { remoteLogoUrl: team.remoteLogoUrl } : {}),
  }
}

function text(value) {
  return typeof value === 'string' ? value.trim() : ''
}

function arrayArg(value) {
  return value === undefined ? [] : Array.isArray(value) ? value : [value]
}

async function mapConcurrent(values, concurrency, callback) {
  const result = new Array(values.length)
  let cursor = 0
  await Promise.all(Array.from({ length: Math.min(concurrency, values.length) }, async () => {
    while (cursor < values.length) {
      const index = cursor
      cursor += 1
      result[index] = await callback(values[index], index)
    }
  }))
  return result
}

function parseArgs(rawArgs) {
  const parsed = {}
  for (let index = 0; index < rawArgs.length; index += 1) {
    const arg = rawArgs[index]
    if (!arg.startsWith('--')) continue
    const key = arg.slice(2)
    const next = rawArgs[index + 1]
    if (!next || next.startsWith('--')) parsed[key] = true
    else {
      const current = parsed[key]
      parsed[key] = current === undefined ? next : Array.isArray(current) ? [...current, next] : [current, next]
      index += 1
    }
  }
  return parsed
}

function sleep(milliseconds) {
  return new Promise((done) => setTimeout(done, milliseconds))
}
